// Install Playwright separately, then run with BASE_URL pointing to the running app.
const {chromium} = require('playwright');
const assert = require('node:assert/strict');
const base = process.env.BASE_URL || 'http://127.0.0.1:3211';
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:process.env.CHROMIUM_PATH||undefined,args:['--no-sandbox']});
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 const visit=async(path)=>{await page.goto(base+path);await page.getByText('이 브라우저에 기록 저장',{exact:false}).waitFor();};
 const heading=()=>page.locator('.lesson-source-header h2');
 const expectSection=async(n)=>{await page.waitForFunction(n=>document.querySelector('.lesson-source-header h2')?.textContent.startsWith(`SECTION ${String(n).padStart(2,'0')}.`),n);};
 await visit('/learn?section=37');await expectSection(37);
 assert.equal(await page.locator('.lesson-prose h3').first().textContent(),'1. 디지털 포렌식과 침해사고 대응');
 assert.ok(!(await page.locator('.lesson-prose').textContent()).includes('SET'));
 await page.getByRole('navigation',{name:'본문 목차'}).getByRole('link').nth(1).click();
 assert.ok(page.url().includes('#section-37-heading-6'));
 await page.reload();await expectSection(37);
 await page.getByRole('button',{name:'다음 단원 →',exact:true}).click();await expectSection(38);
 assert.equal(new URL(page.url()).searchParams.get('section'),'38');
 await page.goBack();await expectSection(37);
 await page.goForward();await expectSection(38);
 const search=page.getByRole('textbox',{name:'단원 검색'});
 await search.fill('tcp');const lower=await page.locator('.section-list section button').allTextContents();
 await search.fill(' TCP ');assert.deepEqual(await page.locator('.section-list section button').allTextContents(),lower);
 assert.ok(lower.some(s=>s.includes('TCP/IP')));
 await search.fill('DORA');assert.equal(await page.locator('.section-list section button').count(),1);
 await page.locator('.section-list section button').click();await expectSection(34);
 await page.getByRole('combobox',{name:'PART'}).selectOption('6');
 await page.reload();await expectSection(34);
 assert.equal(await search.inputValue(),'DORA');assert.equal(await page.getByRole('combobox',{name:'PART'}).inputValue(),'6');
 await search.fill('q519');await page.locator('.section-list section button').click();await expectSection(37);
 await search.fill('없는단원xyz');assert.equal(await page.locator('.section-list section button').count(),0);
 await page.getByRole('button',{name:'검색 조건 초기화'}).click();assert.equal(await page.locator('.section-list section button').count(),42);
 await search.fill('36');await page.locator('.section-list section button').click();await expectSection(36);
 assert.equal(await page.locator('.lesson-prose h3').count(),3);
 await page.getByRole('button',{name:'학습 완료 표시',exact:true}).click();await page.reload();await expectSection(36);
 assert.equal(await page.getByRole('button',{name:'학습 완료 취소'}).getAttribute('aria-pressed'),'true');
 await page.getByRole('navigation',{name:'주 메뉴'}).getByRole('button',{name:'대시보드',exact:true}).click();
 await page.reload();await page.getByRole('heading',{name:'학습자님, 오늘도 한 걸음씩.'}).waitFor();
 await visit('/learn?section=999&part=999');await expectSection(1);
 assert.equal(await page.getByRole('button',{name:'← 이전 단원'}).isDisabled(),true);
 await visit('/learn?section=42');await expectSection(42);assert.equal(await page.getByRole('button',{name:'다음 단원 →'}).isDisabled(),true);
 await page.setViewportSize({width:390,height:844});
 await visit('/learn?section=34');await expectSection(34);
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true,'mobile overflow');
 const table=page.locator('.lesson-table-scroll').first();
 assert.equal(await table.evaluate(e=>e.scrollWidth>e.clientWidth),true,'table scroll');
 await page.setViewportSize({width:1440,height:1000});await visit('/learn?section=37');await expectSection(37);
 assert.deepEqual(errors,[]);
 console.log('PASS: URL refresh/back/forward, headings, TOC, search, filters, empty state, completion persistence, tabs, invalid IDs, boundaries, mobile overflow, runtime errors');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
